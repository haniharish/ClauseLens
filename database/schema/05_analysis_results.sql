-- =============================================================================
-- ClauseLens PostgreSQL Schema - 05_analysis_results.sql
-- Purpose: Aggregate document-level risk scores and clause risk distributions.
-- =============================================================================

CREATE TABLE IF NOT EXISTS analysis_results (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document_id        BIGINT NOT NULL,
    total_clauses      INTEGER NOT NULL DEFAULT 0,
    high_risk_count    INTEGER NOT NULL DEFAULT 0,
    medium_risk_count  INTEGER NOT NULL DEFAULT 0,
    low_risk_count     INTEGER NOT NULL DEFAULT 0,
    overall_risk_score NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    analysis_status    VARCHAR(30) NOT NULL DEFAULT 'Pending',
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_analysis_results PRIMARY KEY (id),
    CONSTRAINT fk_analysis_results_document
        FOREIGN KEY (document_id) REFERENCES documents (id) ON DELETE RESTRICT,
    CONSTRAINT chk_analysis_counts_nonneg CHECK (
        total_clauses >= 0
        AND high_risk_count >= 0
        AND medium_risk_count >= 0
        AND low_risk_count >= 0
    ),
    CONSTRAINT chk_analysis_counts_sum CHECK (
        high_risk_count + medium_risk_count + low_risk_count <= total_clauses
    ),
    CONSTRAINT chk_analysis_overall_score_range CHECK (
        overall_risk_score >= 0.00 AND overall_risk_score <= 100.00
    ),
    CONSTRAINT chk_analysis_status CHECK (
        analysis_status IN ('Pending', 'Processing', 'Completed', 'Failed')
    )
);

CREATE INDEX IF NOT EXISTS idx_analysis_results_document_created
    ON analysis_results (document_id, created_at DESC);

COMMENT ON TABLE analysis_results IS 'Document-level aggregate analysis metrics across time (0-100 risk index).';
