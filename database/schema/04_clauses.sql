-- =============================================================================
-- ClauseLens PostgreSQL Schema - 04_clauses.sql
-- Purpose: Normalized clause categories, extracted legal clauses, and
--          AI-generated plain-language summaries (kept strictly separate).
-- =============================================================================

CREATE TABLE IF NOT EXISTS clause_categories (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code           VARCHAR(50) NOT NULL,
    name           VARCHAR(100) NOT NULL,
    default_weight NUMERIC(4,3) NOT NULL DEFAULT 0.500,
    description    TEXT NOT NULL DEFAULT '',

    CONSTRAINT pk_clause_categories PRIMARY KEY (id),
    CONSTRAINT uq_clause_categories_code UNIQUE (code),
    CONSTRAINT uq_clause_categories_name UNIQUE (name),
    CONSTRAINT chk_clause_categories_weight CHECK (
        default_weight >= 0.000 AND default_weight <= 1.000
    )
);

CREATE TABLE IF NOT EXISTS clauses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document_id    BIGINT NOT NULL,
    category_id    BIGINT NOT NULL,
    clause_title   VARCHAR(255) NOT NULL,
    original_text  TEXT NOT NULL,
    severity_score NUMERIC(4,3) NOT NULL,
    clause_order   INTEGER NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_clauses PRIMARY KEY (id),
    CONSTRAINT uq_clauses_doc_order UNIQUE (document_id, clause_order),
    CONSTRAINT fk_clauses_document
        FOREIGN KEY (document_id) REFERENCES documents (id) ON DELETE RESTRICT,
    CONSTRAINT fk_clauses_category
        FOREIGN KEY (category_id) REFERENCES clause_categories (id) ON DELETE RESTRICT,
    CONSTRAINT chk_clauses_title_nonempty CHECK (CHAR_LENGTH(TRIM(clause_title)) >= 1),
    CONSTRAINT chk_clauses_text_nonempty CHECK (CHAR_LENGTH(TRIM(original_text)) >= 1),
    CONSTRAINT chk_clauses_severity_range CHECK (
        severity_score >= 0.000 AND severity_score <= 1.000
    ),
    CONSTRAINT chk_clauses_order_positive CHECK (clause_order >= 1)
);

CREATE TABLE IF NOT EXISTS clause_summaries (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    clause_id          BIGINT NOT NULL,
    simple_explanation TEXT NOT NULL,
    summary_language   VARCHAR(20) NOT NULL DEFAULT 'en',
    model_name         VARCHAR(100) NOT NULL,
    summary_version    INTEGER NOT NULL DEFAULT 1,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_clause_summaries PRIMARY KEY (id),
    CONSTRAINT uq_clause_summaries_version UNIQUE (
        clause_id, summary_language, model_name, summary_version
    ),
    CONSTRAINT fk_clause_summaries_clause
        FOREIGN KEY (clause_id) REFERENCES clauses (id) ON DELETE CASCADE,
    CONSTRAINT chk_clause_summaries_explanation_nonempty CHECK (
        CHAR_LENGTH(TRIM(simple_explanation)) >= 1
    ),
    CONSTRAINT chk_clause_summaries_model_nonempty CHECK (
        CHAR_LENGTH(TRIM(model_name)) >= 1
    ),
    CONSTRAINT chk_clause_summaries_version_positive CHECK (summary_version >= 1)
);

-- Indexes for clause extraction, filtering, and severity ranking
CREATE INDEX IF NOT EXISTS idx_clauses_document_id
    ON clauses (document_id);

CREATE INDEX IF NOT EXISTS idx_clauses_category_id
    ON clauses (category_id);

CREATE INDEX IF NOT EXISTS idx_clauses_severity_score
    ON clauses (severity_score DESC);

CREATE INDEX IF NOT EXISTS idx_clauses_doc_severity
    ON clauses (document_id, severity_score DESC);

CREATE INDEX IF NOT EXISTS idx_clause_summaries_clause_id
    ON clause_summaries (clause_id);

