"""
ClauseLens – PersonalizedRisk model.
"""
from django.db import models
from django.conf import settings


class PersonalizedRisk(models.Model):
    """
    Personalised relevance score for a clause, computed for a specific user.
    Formula: R(c,u) = S(c)[λ·max(0, cos(ec,eu)) + (1-λ)·L(c,ju,bu)]
    (computed by Member 5's personalization service)
    """

    class RiskLevel(models.TextChoices):
        HIGH = 'High', 'High'
        MEDIUM = 'Medium', 'Medium'
        LOW = 'Low', 'Low'

    id = models.BigAutoField(primary_key=True)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='personalized_risks',
    )
    clause = models.ForeignKey(
        'analysis.Clause',
        on_delete=models.CASCADE,
        related_name='personalized_risks',
    )
    relevance_score = models.FloatField(
        help_text='Score from 0.0 to 1.0; higher = more relevant to this user.',
    )
    risk_level = models.CharField(
        max_length=10,
        choices=RiskLevel.choices,
        default=RiskLevel.MEDIUM,
    )
    why_it_matters = models.TextField(
        help_text='Human-readable explanation generated by the personalization module.',
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'personalized_risks'
        unique_together = [('user', 'clause')]
        ordering = ['-relevance_score']
        indexes = [
            models.Index(fields=['user', 'relevance_score']),
        ]

    def __str__(self):
        return f'PersonalizedRisk(user={self.user_id}, clause={self.clause_id}, score={self.relevance_score})'
