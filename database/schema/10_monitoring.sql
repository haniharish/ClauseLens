-- =============================================================================
-- ClauseLens PostgreSQL Schema - 10_monitoring.sql
-- Purpose: User subscriptions to monitored public policy URLs.
-- Shared Document Model:
--   Multiple users can monitor the same document_id (UNIQUE(user_id, document_id))
--   without duplicating underlying documents, clauses, or policy_versions.
-- =============================================================================

CREATE TABLE IF NOT EXISTS monitored_policies (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id              BIGINT NOT NULL,
    document_id          BIGINT NOT NULL,
    policy_url           VARCHAR(2048) NOT NULL,
    monitoring_status    VARCHAR(20) NOT NULL DEFAULT 'Active',
    check_interval_hours INTEGER NOT NULL DEFAULT 24,
    last_checked_at      TIMESTAMPTZ NULL,
    next_check_at        TIMESTAMPTZ NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_monitored_policies PRIMARY KEY (id),
    CONSTRAINT uq_monitored_policies_user_doc UNIQUE (user_id, document_id),
    CONSTRAINT fk_monitored_policies_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_monitored_policies_document
        FOREIGN KEY (document_id) REFERENCES documents (id) ON DELETE RESTRICT,
    CONSTRAINT chk_monitored_policies_url_scheme CHECK (
        policy_url ~* '^https?://'
    ),
    CONSTRAINT chk_monitored_policies_status CHECK (
        monitoring_status IN ('Active', 'Paused', 'Failed')
    ),
    CONSTRAINT chk_monitored_policies_interval CHECK (check_interval_hours >= 1),
    CONSTRAINT chk_monitored_policies_schedule_order CHECK (
        last_checked_at IS NULL
        OR next_check_at IS NULL
        OR next_check_at >= last_checked_at
    )
);

CREATE INDEX IF NOT EXISTS idx_monitored_policies_user_id
    ON monitored_policies (user_id);

CREATE INDEX IF NOT EXISTS idx_monitored_policies_status
    ON monitored_policies (monitoring_status);

CREATE INDEX IF NOT EXISTS idx_monitored_policies_due_checks
    ON monitored_policies (monitoring_status, next_check_at)
    WHERE monitoring_status = 'Active';

DROP TRIGGER IF EXISTS trg_monitored_policies_set_updated_at ON monitored_policies;
CREATE TRIGGER trg_monitored_policies_set_updated_at
    BEFORE UPDATE ON monitored_policies
    FOR EACH ROW
    EXECUTE FUNCTION fn_set_updated_at();

COMMENT ON TABLE monitored_policies IS 'Tracks user subscriptions and polling schedules for public policies.';
