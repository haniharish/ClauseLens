-- =============================================================================
-- ClauseLens PostgreSQL Schema - 07_policy_versions.sql
-- Purpose: Immutable snapshot history and SHA-256 content hashes for monitored
--          and re-analyzed legal documents (Member 6).
-- Retention Rule:
--   Uses ON DELETE RESTRICT on document_id so historical policy evidence cannot
--   be accidentally destroyed by cascading deletes.
-- =============================================================================

CREATE TABLE IF NOT EXISTS policy_versions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document_id      BIGINT NOT NULL,
    version_number   VARCHAR(30) NOT NULL,
    version_sequence INTEGER NOT NULL,
    version_text     TEXT NULL,
    stored_reference VARCHAR(500) NULL,
    content_hash     CHAR(64) NOT NULL,
    fetched_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_policy_versions PRIMARY KEY (id),
    CONSTRAINT uq_policy_versions_doc_number UNIQUE (document_id, version_number),
    CONSTRAINT uq_policy_versions_doc_seq UNIQUE (document_id, version_sequence),
    CONSTRAINT uq_policy_versions_doc_hash UNIQUE (document_id, content_hash),
    CONSTRAINT fk_policy_versions_document
        FOREIGN KEY (document_id) REFERENCES documents (id) ON DELETE RESTRICT,
    CONSTRAINT chk_policy_versions_number_nonempty CHECK (
        CHAR_LENGTH(TRIM(version_number)) >= 1
    ),
    CONSTRAINT chk_policy_versions_seq_positive CHECK (version_sequence >= 1),
    CONSTRAINT chk_policy_versions_content_present CHECK (
        version_text IS NOT NULL OR stored_reference IS NOT NULL
    ),
    CONSTRAINT chk_policy_versions_sha256_hex CHECK (
        content_hash ~ '^[0-9a-fA-F]{64}$'
    )
);

CREATE INDEX IF NOT EXISTS idx_policy_versions_document_id
    ON policy_versions (document_id);

CREATE INDEX IF NOT EXISTS idx_policy_versions_content_hash
    ON policy_versions (content_hash);

CREATE INDEX IF NOT EXISTS idx_policy_versions_doc_seq
    ON policy_versions (document_id, version_sequence DESC);

COMMENT ON TABLE policy_versions IS 'Historical policy snapshots with SHA-256 deduplication per document.';
