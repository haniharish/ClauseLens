-- =============================================================================
-- ClauseLens PostgreSQL Schema - 02_profiles.sql
-- Purpose: Normalized (3NF) user profile context for personalized risk scoring.
-- Contains:
--   - age_groups (lookup)
--   - jurisdictions (lookup)
--   - intended_use_categories (lookup)
--   - user_profiles (1:1 with users)
--   - user_profile_intended_uses (M:N junction between profiles & intended uses)
-- =============================================================================

CREATE TABLE IF NOT EXISTS age_groups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code        VARCHAR(32) NOT NULL,
    label       VARCHAR(50) NOT NULL,
    min_age     SMALLINT NOT NULL,
    max_age     SMALLINT NULL,
    description TEXT NOT NULL DEFAULT '',

    CONSTRAINT pk_age_groups PRIMARY KEY (id),
    CONSTRAINT uq_age_groups_code UNIQUE (code),
    CONSTRAINT uq_age_groups_label UNIQUE (label),
    CONSTRAINT chk_age_groups_range CHECK (
        min_age >= 0 AND (max_age IS NULL OR max_age >= min_age)
    )
);

CREATE TABLE IF NOT EXISTS jurisdictions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code                VARCHAR(32) NOT NULL,
    name                VARCHAR(100) NOT NULL,
    primary_framework   VARCHAR(150) NOT NULL DEFAULT '',
    description         TEXT NOT NULL DEFAULT '',

    CONSTRAINT pk_jurisdictions PRIMARY KEY (id),
    CONSTRAINT uq_jurisdictions_code UNIQUE (code),
    CONSTRAINT uq_jurisdictions_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS intended_use_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code        VARCHAR(32) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description TEXT NOT NULL DEFAULT '',

    CONSTRAINT pk_intended_use_categories PRIMARY KEY (id),
    CONSTRAINT uq_intended_use_code UNIQUE (code),
    CONSTRAINT uq_intended_use_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS user_profiles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT NOT NULL,
    age_group_id    BIGINT NOT NULL,
    jurisdiction_id BIGINT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_user_profiles PRIMARY KEY (id),
    CONSTRAINT uq_user_profiles_user_id UNIQUE (user_id),
    CONSTRAINT fk_user_profiles_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_profiles_age_group
        FOREIGN KEY (age_group_id) REFERENCES age_groups (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_profiles_jurisdiction
        FOREIGN KEY (jurisdiction_id) REFERENCES jurisdictions (id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS user_profile_intended_uses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_profile_id BIGINT NOT NULL,
    intended_use_id BIGINT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_user_profile_intended_uses PRIMARY KEY (id),
    CONSTRAINT uq_profile_intended_use UNIQUE (user_profile_id, intended_use_id),
    CONSTRAINT fk_upiu_profile
        FOREIGN KEY (user_profile_id) REFERENCES user_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_upiu_intended_use
        FOREIGN KEY (intended_use_id) REFERENCES intended_use_categories (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_user_profiles_age_group
    ON user_profiles (age_group_id);

CREATE INDEX IF NOT EXISTS idx_user_profiles_jurisdiction
    ON user_profiles (jurisdiction_id);

CREATE INDEX IF NOT EXISTS idx_upiu_intended_use
    ON user_profile_intended_uses (intended_use_id);

DROP TRIGGER IF EXISTS trg_user_profiles_set_updated_at ON user_profiles;
CREATE TRIGGER trg_user_profiles_set_updated_at
    BEFORE UPDATE ON user_profiles
    FOR EACH ROW
    EXECUTE FUNCTION fn_set_updated_at();

