-- =============================================================================
-- ClauseLens PostgreSQL Schema - 09_notifications.sql
-- Purpose: Personalized policy change alerts and system notifications.
-- Deduplication:
--   Partial unique index prevents duplicate alerts for the same (user_id, policy_change_id)
--   while allowing multiple system notifications where policy_change_id IS NULL.
-- =============================================================================

CREATE TABLE IF NOT EXISTS notifications (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT NOT NULL,
    policy_change_id BIGINT NULL,
    title            VARCHAR(255) NOT NULL,
    message          TEXT NOT NULL,
    alert_score      NUMERIC(4,3) NOT NULL DEFAULT 0.000,
    severity         VARCHAR(20) NOT NULL DEFAULT 'Info',
    is_read          BOOLEAN NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT fk_notifications_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_policy_change
        FOREIGN KEY (policy_change_id) REFERENCES policy_changes (id) ON DELETE SET NULL,
    CONSTRAINT chk_notifications_title_nonempty CHECK (CHAR_LENGTH(TRIM(title)) >= 1),
    CONSTRAINT chk_notifications_message_nonempty CHECK (CHAR_LENGTH(TRIM(message)) >= 1),
    CONSTRAINT chk_notifications_alert_score_range CHECK (
        alert_score >= 0.000 AND alert_score <= 1.000
    ),
    CONSTRAINT chk_notifications_severity CHECK (
        severity IN ('Info', 'Low', 'Medium', 'High', 'Critical')
    )
);

-- Prevent duplicate alerts for the same user and policy change
CREATE UNIQUE INDEX IF NOT EXISTS uq_notifications_user_policy_change
    ON notifications (user_id, policy_change_id)
    WHERE policy_change_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_notifications_user_id
    ON notifications (user_id);

CREATE INDEX IF NOT EXISTS idx_notifications_is_read
    ON notifications (is_read);

CREATE INDEX IF NOT EXISTS idx_notifications_user_unread_recent
    ON notifications (user_id, is_read, created_at DESC);

COMMENT ON TABLE notifications IS 'Personalized version-diff and risk alerts delivered to users.';
