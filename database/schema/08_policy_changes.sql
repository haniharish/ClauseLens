-- =============================================================================
-- ClauseLens PostgreSQL Schema - 08_policy_changes.sql
-- Purpose: Clause-level diff records (Added, Removed, Modified, Unchanged)
--          between old and new policy_versions (Member 6).
-- =============================================================================

CREATE TABLE IF NOT EXISTS policy_changes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document_id      BIGINT NOT NULL,
    old_version_id   BIGINT NOT NULL,
    new_version_id   BIGINT NOT NULL,
    old_clause_id    BIGINT NULL,
    new_clause_id    BIGINT NULL,
    change_type      VARCHAR(20) NOT NULL,
    change_direction VARCHAR(20) NOT NULL,
    magnitude        NUMERIC(4,3) NOT NULL,
    change_summary   TEXT NULL,
    detected_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_policy_changes PRIMARY KEY (id),
    CONSTRAINT fk_policy_changes_document
        FOREIGN KEY (document_id) REFERENCES documents (id) ON DELETE RESTRICT,
    CONSTRAINT fk_policy_changes_old_version
        FOREIGN KEY (old_version_id) REFERENCES policy_versions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_policy_changes_new_version
        FOREIGN KEY (new_version_id) REFERENCES policy_versions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_policy_changes_old_clause
        FOREIGN KEY (old_clause_id) REFERENCES clauses (id) ON DELETE SET NULL,
    CONSTRAINT fk_policy_changes_new_clause
        FOREIGN KEY (new_clause_id) REFERENCES clauses (id) ON DELETE SET NULL,
    CONSTRAINT chk_policy_changes_distinct_versions CHECK (
        old_version_id <> new_version_id
    ),
    CONSTRAINT chk_policy_changes_type CHECK (
        change_type IN ('Added', 'Removed', 'Modified', 'Unchanged')
    ),
    CONSTRAINT chk_policy_changes_direction CHECK (
        change_direction IN ('More Favorable', 'Neutral', 'Less Favorable', 'Unclear')
    ),
    CONSTRAINT chk_policy_changes_magnitude_range CHECK (
        magnitude >= 0.000 AND magnitude <= 1.000
    ),
    CONSTRAINT chk_policy_changes_clause_presence CHECK (
        (change_type = 'Added' AND old_clause_id IS NULL AND new_clause_id IS NOT NULL)
        OR (change_type = 'Removed' AND old_clause_id IS NOT NULL AND new_clause_id IS NULL)
        OR (change_type IN ('Modified', 'Unchanged') AND old_clause_id IS NOT NULL AND new_clause_id IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_policy_changes_document_id
    ON policy_changes (document_id);

CREATE INDEX IF NOT EXISTS idx_policy_changes_versions
    ON policy_changes (old_version_id, new_version_id);

CREATE INDEX IF NOT EXISTS idx_policy_changes_type_detected
    ON policy_changes (change_type, detected_at DESC);

CREATE INDEX IF NOT EXISTS idx_policy_changes_detected_at
    ON policy_changes (detected_at DESC);

COMMENT ON TABLE policy_changes IS 'Version-diff records tracking added, removed, and modified clauses with direction and magnitude.';
