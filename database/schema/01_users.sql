-- =============================================================================
-- ClauseLens PostgreSQL Schema - 01_users.sql
-- Purpose: Shared trigger utilities and authoritative user account table.
-- Django Integration: Maps to Member 2's custom User model (db_table = 'users')
--   inheriting AbstractBaseUser + PermissionsMixin.
--   Passwords MUST be Django-formatted hashes (PBKDF2/Argon2), never plaintext.
-- =============================================================================

-- Shared trigger function to automatically maintain updated_at timestamps.
CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username        VARCHAR(150) NOT NULL,
    full_name       VARCHAR(255) NOT NULL,
    email           VARCHAR(254) NOT NULL,
    password        VARCHAR(128) NOT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    is_staff        BOOLEAN NOT NULL DEFAULT FALSE,
    is_superuser    BOOLEAN NOT NULL DEFAULT FALSE,
    last_login      TIMESTAMPTZ NULL,
    date_joined     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_username_len CHECK (CHAR_LENGTH(TRIM(username)) >= 3),
    CONSTRAINT chk_users_full_name_nonempty CHECK (CHAR_LENGTH(TRIM(full_name)) >= 1),
    CONSTRAINT chk_users_email_format CHECK (
        email ~* '^[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}$'
    ),
    -- Ensures stored passwords look like hashed digests rather than short plaintext
    CONSTRAINT chk_users_password_hashed_len CHECK (CHAR_LENGTH(password) >= 20)
);

-- Indexes for fast authentication and case-insensitive email lookup
CREATE INDEX IF NOT EXISTS idx_users_email
    ON users (email);

CREATE INDEX IF NOT EXISTS idx_users_email_lower
    ON users (LOWER(email));

CREATE INDEX IF NOT EXISTS idx_users_active
    ON users (is_active)
    WHERE is_active = TRUE;

DROP TRIGGER IF EXISTS trg_users_set_updated_at ON users;
CREATE TRIGGER trg_users_set_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW
    EXECUTE FUNCTION fn_set_updated_at();

COMMENT ON TABLE users IS 'Authoritative ClauseLens user accounts managed through Django authentication.';
COMMENT ON COLUMN users.password IS 'Django-managed password hash (PBKDF2/Argon2). Plain-text passwords are prohibited.';
