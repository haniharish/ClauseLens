-- =============================================================================
-- ClauseLens PostgreSQL Schema - 03_documents.sql
-- Purpose: Metadata and processing status for uploaded PDFs and policy URLs.
-- Retention Policy:
--   - File binaries are stored in object/media storage, referenced via file_path.
--   - user_id uses ON DELETE SET NULL so deleting a user anonymizes ownership
--     without destroying shared public policies or historical version evidence.
-- =============================================================================

CREATE TABLE IF NOT EXISTS documents (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id           BIGINT NULL,
    document_name     VARCHAR(255) NOT NULL,
    document_type     VARCHAR(50) NOT NULL,
    file_path         VARCHAR(500) NULL,
    policy_url        VARCHAR(2048) NULL,
    source_type       VARCHAR(30) NOT NULL,
    processing_status VARCHAR(30) NOT NULL DEFAULT 'Uploaded',
    is_public_policy  BOOLEAN NOT NULL DEFAULT FALSE,
    is_deleted        BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at        TIMESTAMPTZ NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_documents PRIMARY KEY (id),
    CONSTRAINT fk_documents_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_documents_name_nonempty CHECK (CHAR_LENGTH(TRIM(document_name)) >= 1),
    CONSTRAINT chk_documents_type CHECK (
        document_type IN ('Terms and Conditions', 'Privacy Policy', 'Other Legal Document')
    ),
    CONSTRAINT chk_documents_source_type CHECK (
        source_type IN ('PDF Upload', 'URL', 'Manual Text')
    ),
    CONSTRAINT chk_documents_processing_status CHECK (
        processing_status IN ('Uploaded', 'Pending', 'Processing', 'Completed', 'Failed')
    ),
    CONSTRAINT chk_documents_source_reference CHECK (
        (source_type = 'PDF Upload' AND file_path IS NOT NULL AND CHAR_LENGTH(TRIM(file_path)) > 0)
        OR (source_type = 'URL' AND policy_url IS NOT NULL AND CHAR_LENGTH(TRIM(policy_url)) > 0)
        OR (source_type = 'Manual Text')
    ),
    CONSTRAINT chk_documents_url_scheme CHECK (
        policy_url IS NULL OR policy_url ~* '^https?://'
    ),
    CONSTRAINT chk_documents_soft_delete_consistency CHECK (
        (is_deleted = FALSE AND deleted_at IS NULL)
        OR (is_deleted = TRUE AND deleted_at IS NOT NULL)
    )
);

-- Core indexes required for dashboard and document management queries
CREATE INDEX IF NOT EXISTS idx_documents_user_id
    ON documents (user_id);

CREATE INDEX IF NOT EXISTS idx_documents_created_at
    ON documents (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_documents_user_active_created
    ON documents (user_id, created_at DESC)
    WHERE is_deleted = FALSE;

CREATE INDEX IF NOT EXISTS idx_documents_processing_status
    ON documents (processing_status);

CREATE INDEX IF NOT EXISTS idx_documents_public_url
    ON documents (policy_url)
    WHERE is_public_policy = TRUE AND policy_url IS NOT NULL;

DROP TRIGGER IF EXISTS trg_documents_set_updated_at ON documents;
CREATE TRIGGER trg_documents_set_updated_at
    BEFORE UPDATE ON documents
    FOR EACH ROW
    EXECUTE FUNCTION fn_set_updated_at();

COMMENT ON TABLE documents IS 'Stores legal document metadata, source references, and NLP pipeline status.';
COMMENT ON COLUMN documents.user_id IS 'Document uploader; nullable with ON DELETE SET NULL to preserve shared policy history.';
