"""
ClauseLens – Clause and AnalysisResult models.
"""
from django.db import models


class Clause(models.Model):
    """
    A single clause extracted from a document by the NLP module.
    """

    class Category(models.TextChoices):
        DATA_COLLECTION = 'data_collection', 'Data Collection'
        DATA_SHARING = 'data_sharing', 'Data Sharing'
        DATA_RETENTION = 'data_retention', 'Data Retention'
        ARBITRATION = 'arbitration', 'Arbitration and Jurisdiction'
        LIABILITY = 'liability', 'Liability Limitation'
        UNILATERAL_CHANGE = 'unilateral_change', 'Unilateral Change of Terms'
        AUTO_RENEWAL = 'auto_renewal', 'Auto-renewal and Fees'
        CONTENT_LICENSE = 'content_license', 'Content License'
        ACCOUNT_TERMINATION = 'account_termination', 'Account Termination'
        CHILDREN_AGE = 'children_age', 'Children and Age'
        OTHER = 'other', 'Other'

    id = models.BigAutoField(primary_key=True)
    document = models.ForeignKey(
        'documents.Document',
        on_delete=models.CASCADE,
        related_name='clauses',
    )
    clause_title = models.CharField(max_length=500)
    original_text = models.TextField()
    category = models.CharField(
        max_length=25,
        choices=Category.choices,
        default=Category.OTHER,
        db_index=True,
    )
    severity = models.FloatField(
        help_text='Severity score from 0.0 (low) to 1.0 (high), assigned by the NLP module.',
        default=0.0,
    )
    simple_explanation = models.TextField(
        help_text='Plain-language summary generated by the NLP module.',
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'clauses'
        ordering = ['-severity']
        indexes = [
            models.Index(fields=['document', 'category']),
            models.Index(fields=['severity']),
        ]

    def __str__(self):
        return f'Clause({self.id}) – {self.clause_title}'


class AnalysisResult(models.Model):
    """
    Aggregate summary of the NLP analysis for a document.
    One record per document.
    """

    class AnalysisStatus(models.TextChoices):
        PENDING = 'pending', 'Pending'
        IN_PROGRESS = 'in_progress', 'In Progress'
        COMPLETED = 'completed', 'Completed'
        FAILED = 'failed', 'Failed'

    id = models.BigAutoField(primary_key=True)
    document = models.OneToOneField(
        'documents.Document',
        on_delete=models.CASCADE,
        related_name='analysis_result',
    )
    total_clauses = models.PositiveIntegerField(default=0)
    high_risk_count = models.PositiveIntegerField(default=0)
    medium_risk_count = models.PositiveIntegerField(default=0)
    low_risk_count = models.PositiveIntegerField(default=0)
    overall_risk_score = models.FloatField(default=0.0)
    analysis_status = models.CharField(
        max_length=15,
        choices=AnalysisStatus.choices,
        default=AnalysisStatus.PENDING,
        db_index=True,
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'analysis_results'

    def __str__(self):
        return f'Analysis(doc={self.document_id}, status={self.analysis_status})'
