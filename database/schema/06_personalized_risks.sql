-- =============================================================================
-- ClauseLens PostgreSQL Schema - 06_personalized_risks.sql
-- Purpose: Personalized clause relevance scores and user-tailored explanations
--          produced by Member 5's Personalization and Risk Analysis module.
-- =============================================================================

CREATE TABLE IF NOT EXISTS personalized_risks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT NOT NULL,
    clause_id       BIGINT NOT NULL,
    relevance_score NUMERIC(4,3) NOT NULL,
    risk_level      VARCHAR(20) NOT NULL,
    why_it_matters  TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_personalized_risks PRIMARY KEY (id),
    CONSTRAINT uq_personalized_risks_user_clause UNIQUE (user_id, clause_id),
    CONSTRAINT fk_personalized_risks_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_personalized_risks_clause
        FOREIGN KEY (clause_id) REFERENCES clauses (id) ON DELETE CASCADE,
    CONSTRAINT chk_personalized_risks_score_range CHECK (
        relevance_score >= 0.000 AND relevance_score <= 1.000
    ),
    CONSTRAINT chk_personalized_risks_level CHECK (
        risk_level IN ('Low', 'Medium', 'High', 'Critical')
    ),
    CONSTRAINT chk_personalized_risks_why_nonempty CHECK (
        CHAR_LENGTH(TRIM(why_it_matters)) >= 1
    )
);

-- Indexes for fast per-user clause ranking and cross-user clause lookup
CREATE INDEX IF NOT EXISTS idx_personalized_risks_user_id
    ON personalized_risks (user_id);

CREATE INDEX IF NOT EXISTS idx_personalized_risks_relevance_score
    ON personalized_risks (relevance_score DESC);

CREATE INDEX IF NOT EXISTS idx_personalized_risks_user_relevance
    ON personalized_risks (user_id, relevance_score DESC);

CREATE INDEX IF NOT EXISTS idx_personalized_risks_clause_id
    ON personalized_risks (clause_id);

COMMENT ON TABLE personalized_risks IS 'Stores user-specific clause relevance scores (0-1) and contextual explanations.';
